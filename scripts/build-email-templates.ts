/**
 * Builds the sign-in email texts from messages/*.json, so they follow the same translation and
 * review flow as the interface (translations.csv, review.json, check:i18n).
 *
 *   npm run email:build            writes the files below
 *   npm run email:build -- --check fails if they are out of date (part of npm run lint)
 *
 * - supabase/functions/send-email/copy.gen.ts: the texts per language for the Send Email Hook,
 *   which sends every email in the language of the page (deploy the function after a change).
 * - supabase/templates/*.html and the subjects in config.toml: the fallback when the hook is
 *   off. One template per project, the language picked with Go template conditions on the
 *   user's metadata ({{ .Data.locale }}); applied with `npx supabase config push`.
 *
 * Both use the layout of supabase/functions/send-email/render.ts.
 *
 * The link puts the token in the fragment (#token_hash=…): valid whether or not RedirectTo
 * already has a query string, and never sent to a server or written in its logs.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { APP_NAME, OTP_EXPIRY_SECONDS } from '../src/lib/config.ts';
import { emailBody, emailLayout, type EmailCopy } from '../supabase/functions/send-email/render.ts';
import { SOURCE_LOCALE, TRANSLATED_LOCALES, readMessages, type Messages } from './i18n-messages.ts';

const TEMPLATES_DIR = path.join('supabase', 'templates');
const CONFIG_FILE = path.join('supabase', 'config.toml');
const COPY_FILE = path.join('supabase', 'functions', 'send-email', 'copy.gen.ts');
// New users get the confirmation email, returning users the magic link: same content.
const TEMPLATES = ['magic_link', 'confirmation'] as const;
const LOCALES = [SOURCE_LOCALE, ...TRANSLATED_LOCALES];
const check = process.argv.includes('--check');

const values: Record<string, string> = {
	app: APP_NAME,
	minutes: String(OTP_EXPIRY_SECONDS / 60)
};

function text(messages: Messages, key: string): string {
	const message = messages[key];
	if (typeof message !== 'string') throw new Error(`${key}: expected a plain text message`);
	if (message.includes('{{')) throw new Error(`${key}: "{{" would break the Go template`);
	return message.replace(/\{(\w+)\}/g, (_, name: string) => {
		if (!(name in values)) throw new Error(`${key}: unknown variable {${name}}`);
		return values[name];
	});
}

/** {{ if eq .Data.locale "es" }}…{{ else if … }}…{{ else }}English{{ end }} */
function byLocale(render: (locale: string) => string): string {
	const [fallback, ...others] = LOCALES;
	const branches = others.map(
		(locale, i) =>
			`{{ ${i === 0 ? 'if' : 'else if'} eq .Data.locale "${locale}" }}${render(locale)}`
	);
	return `${branches.join('')}{{ else }}${render(fallback)}{{ end }}`;
}

const all = Object.fromEntries(
	await Promise.all(LOCALES.map(async (locale) => [locale, await readMessages(locale)]))
) as Record<string, Messages>;
const KEYS: Record<keyof EmailCopy, string> = {
	subject: 'email_signin_subject',
	title: 'email_signin_title',
	codeIntro: 'email_signin_code_intro',
	linkIntro: 'email_signin_link_intro',
	button: 'email_signin_button',
	expiry: 'email_signin_expiry',
	ignore: 'email_signin_ignore'
};
const copy = (locale: string) =>
	Object.fromEntries(
		Object.entries(KEYS).map(([field, key]) => [field, text(all[locale], key)])
	) as EmailCopy;

const copyFile = `// Generated by scripts/build-email-templates.ts from messages/*.json: do not edit.
import type { EmailCopy } from './render.ts';

export const EMAIL_APP_NAME = ${JSON.stringify(APP_NAME)};

export const EMAIL_LOCALES = ${JSON.stringify(LOCALES)} as const;

export const EMAIL_COPY: Record<(typeof EMAIL_LOCALES)[number], EmailCopy> = ${JSON.stringify(
	Object.fromEntries(LOCALES.map((locale) => [locale, copy(locale)])),
	null,
	'\t'
)};
`;

// Go template placeholders, inserted as they are.
const GO_CODE = '{{ .Token }}';
const GO_LINK = '{{ .RedirectTo }}#token_hash={{ .TokenHash }}&amp;type=email';

const html = `<!-- Generated by scripts/build-email-templates.ts from messages/*.json: do not edit. -->
${emailLayout({
	app: APP_NAME,
	lang: byLocale((locale) => locale),
	body: byLocale((locale) => emailBody(copy(locale), GO_CODE, GO_LINK))
})}`;

// The subject also picks the language; TOML strings need their quotes escaped.
const subject = byLocale((locale) => text(all[locale], 'email_signin_subject')).replace(
	/"/g,
	'\\"'
);

const config = await readFile(CONFIG_FILE, 'utf8');
let newConfig = config;
for (const name of TEMPLATES) {
	const section = new RegExp(`(\\[auth\\.email\\.template\\.${name}\\]\\nsubject = ")(.*)(")`);
	if (!section.test(newConfig))
		throw new Error(`${CONFIG_FILE}: [auth.email.template.${name}] not found`);
	newConfig = newConfig.replace(
		section,
		(_, start: string, _old: string, end: string) => start + subject + end
	);
}

const outputs: [string, string][] = [
	...TEMPLATES.map((name): [string, string] => [path.join(TEMPLATES_DIR, `${name}.html`), html]),
	[CONFIG_FILE, newConfig],
	[COPY_FILE, copyFile]
];

const stale: string[] = [];
for (const [file, content] of outputs) {
	const current = await readFile(file, 'utf8').catch(() => '');
	if (current === content) continue;
	if (check) stale.push(file);
	else await writeFile(file, content);
}

if (check && stale.length) {
	console.error(
		`✖ Email templates out of date (run npm run email:build):\n  ${stale.join('\n  ')}`
	);
	process.exit(1);
}
console.log(
	check
		? '✔ Email texts up to date.'
		: `✔ Email texts written to ${TEMPLATES_DIR} and ${COPY_FILE}.`
);
