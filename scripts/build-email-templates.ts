/**
 * Builds the sign-in email templates from messages/*.json, so the email texts follow the same
 * translation and review flow as the interface (translations.csv, review.json, check:i18n).
 *
 *   npm run email:build            writes supabase/templates/*.html and the subjects in config.toml
 *   npm run email:build -- --check fails if the files are out of date (part of npm run lint)
 *
 * Supabase has one template per project: the language is picked inside it with Go template
 * conditions on the user's metadata ({{ .Data.locale }}, kept in step with profiles.locale).
 * Unknown or missing locale → English. Apply to the project with `npx supabase config push`.
 *
 * The link puts the token in the fragment (#token_hash=…): valid whether or not RedirectTo
 * already has a query string, and never sent to a server or written in its logs.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { APP_NAME, OTP_EXPIRY_SECONDS } from '../src/lib/config.ts';
import { SOURCE_LOCALE, TRANSLATED_LOCALES, readMessages, type Messages } from './i18n-messages.ts';

const TEMPLATES_DIR = path.join('supabase', 'templates');
const CONFIG_FILE = path.join('supabase', 'config.toml');
// New users get the confirmation email, returning users the magic link: same content.
const TEMPLATES = ['magic_link', 'confirmation'] as const;
const LOCALES = [SOURCE_LOCALE, ...TRANSLATED_LOCALES];
const check = process.argv.includes('--check');

const escapeHtml = (text: string) =>
	text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const values: Record<string, string> = {
	app: APP_NAME,
	minutes: String(OTP_EXPIRY_SECONDS / 60)
};

function text(messages: Messages, key: string): string {
	const message = messages[key];
	if (typeof message !== 'string') throw new Error(`${key}: expected a plain text message`);
	if (message.includes('{{')) throw new Error(`${key}: "{{" would break the Go template`);
	return message.replace(/\{(\w+)\}/g, (_, name: string) => {
		if (!(name in values)) throw new Error(`${key}: unknown variable {${name}}`);
		return values[name];
	});
}

/** {{ if eq .Data.locale "es" }}…{{ else if … }}…{{ else }}English{{ end }} */
function byLocale(render: (locale: string) => string): string {
	const [fallback, ...others] = LOCALES;
	const branches = others.map(
		(locale, i) =>
			`{{ ${i === 0 ? 'if' : 'else if'} eq .Data.locale "${locale}" }}${render(locale)}`
	);
	return `${branches.join('')}{{ else }}${render(fallback)}{{ end }}`;
}

const all = Object.fromEntries(
	await Promise.all(LOCALES.map(async (locale) => [locale, await readMessages(locale)]))
) as Record<string, Messages>;
const t = (locale: string, key: string) => escapeHtml(text(all[locale], key));

const body = (locale: string) => `
		<h1 style="margin: 0 0 16px; font-size: 26px; font-weight: 800; letter-spacing: -0.03em; line-height: 1.1">${t(locale, 'email_signin_title')}</h1>
		<p style="margin: 0 0 12px; font-size: 15px; line-height: 1.5; color: #6b5d53">${t(locale, 'email_signin_code_intro')}</p>
		<p style="margin: 0 0 24px; font-family: ui-monospace, Menlo, monospace; font-size: 34px; font-weight: 600; letter-spacing: 0.2em">{{ .Token }}</p>
		<p style="margin: 0 0 12px; font-size: 15px; line-height: 1.5; color: #6b5d53">${t(locale, 'email_signin_link_intro')}</p>
		<p style="margin: 0 0 24px"><a href="{{ .RedirectTo }}#token_hash={{ .TokenHash }}&amp;type=email" style="display: inline-block; padding: 16px 28px; border-radius: 16px; background: #1f1712; color: #faf7f3; font-size: 16px; font-weight: 700; text-decoration: none">${t(locale, 'email_signin_button')}</a></p>
		<p style="margin: 0 0 8px; font-size: 13px; line-height: 1.5; color: #6b5d53">${t(locale, 'email_signin_expiry')}</p>
		<p style="margin: 0; font-size: 13px; line-height: 1.5; color: #6b5d53">${t(locale, 'email_signin_ignore')}</p>
	`;

const html = `<!-- Generated by scripts/build-email-templates.ts from messages/*.json: do not edit. -->
<!doctype html>
<html lang="${byLocale((locale) => locale)}">
<head>
	<meta charset="utf-8" />
	<meta name="viewport" content="width=device-width, initial-scale=1" />
</head>
<body style="margin: 0; padding: 32px 20px; background: #faf7f3; color: #1f1712; font-family: system-ui, -apple-system, 'Segoe UI', sans-serif">
	<div style="max-width: 480px; margin: 0 auto; padding: 28px 24px; border-radius: 20px; background: #ffffff">
		<p style="margin: 0 0 20px; font-size: 18px; font-weight: 800; letter-spacing: -0.03em; color: #6b5d53">${escapeHtml(APP_NAME)}</p>${byLocale(body)}
	</div>
</body>
</html>
`;

// The subject also picks the language; TOML strings need their quotes escaped.
const subject = byLocale((locale) => text(all[locale], 'email_signin_subject')).replace(
	/"/g,
	'\\"'
);

const config = await readFile(CONFIG_FILE, 'utf8');
let newConfig = config;
for (const name of TEMPLATES) {
	const section = new RegExp(`(\\[auth\\.email\\.template\\.${name}\\]\\nsubject = ")(.*)(")`);
	if (!section.test(newConfig))
		throw new Error(`${CONFIG_FILE}: [auth.email.template.${name}] not found`);
	newConfig = newConfig.replace(
		section,
		(_, start: string, _old: string, end: string) => start + subject + end
	);
}

const outputs: [string, string][] = [
	...TEMPLATES.map((name): [string, string] => [path.join(TEMPLATES_DIR, `${name}.html`), html]),
	[CONFIG_FILE, newConfig]
];

const stale: string[] = [];
for (const [file, content] of outputs) {
	const current = await readFile(file, 'utf8').catch(() => '');
	if (current === content) continue;
	if (check) stale.push(file);
	else await writeFile(file, content);
}

if (check && stale.length) {
	console.error(
		`✖ Email templates out of date (run npm run email:build):\n  ${stale.join('\n  ')}`
	);
	process.exit(1);
}
console.log(
	check ? '✔ Email templates up to date.' : `✔ Email templates written to ${TEMPLATES_DIR}.`
);
